"""The one write-class tool: save a Markdown report. Disabled unless AGENT_ALLOW_WRITE=1."""

from __future__ import annotations

import re
from datetime import datetime
from typing import Any

from pydantic import Field

from factory_energy.tools.context import Arguments, ToolContext
from factory_energy.tools.registry import Tool

HEADER = "*Generated by the DemoTronics energy agent from synthetic data for a fictional plant.*"


class ReportArgs(Arguments):
    title: str = Field(min_length=3, max_length=120)
    body_markdown: str = Field(min_length=10, max_length=20_000)
    citations: list[str] = Field(default_factory=list, max_length=30)


def _slug(title: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", title.lower()).strip("-")[:60] or "report"


def generate_report(ctx: ToolContext, args: ReportArgs) -> dict[str, Any]:
    folder = ctx.report_dir.resolve()
    folder.mkdir(parents=True, exist_ok=True)
    path = (folder / f"{datetime.now():%Y%m%d-%H%M%S}-{_slug(args.title)}.md").resolve()
    if path.parent != folder:  # the slug cannot escape the report folder, but check anyway
        raise ValueError("report path escapes the report folder")
    sources = "".join(f"- {c}\n" for c in args.citations)
    text = f"# {args.title}\n\n{HEADER}\n\n{args.body_markdown.strip()}\n"
    if sources:
        text += f"\n## Sources\n\n{sources}"
    path.write_text(text, encoding="utf-8")
    return {"path": path.name, "folder": str(folder), "characters": len(text)}


TOOLS = [
    Tool("generate_report",
         "Save a Markdown report (title, body, citations) to the reports folder. Write-class: "
         "only available when writing is enabled.",
         ReportArgs, "write", generate_report),
]
